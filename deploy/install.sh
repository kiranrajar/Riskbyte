#!/usr/bin/env bash
# ==============================================================================
# RiskByte SOC Agent — Enterprise On-Premises Automated Installer
# Platform: Linux (Ubuntu 22.04+, RHEL 9+, Debian 12+)
# Mode: Air-Gapped Evaluation or Production Docker Compose
# ==============================================================================
set -euo pipefail

COLOR_CYAN="\033[0;36m"
COLOR_GREEN="\033[0;32m"
COLOR_AMBER="\033[0;33m"
COLOR_RED="\033[0;31m"
COLOR_RESET="\033[0m"

echo -e "${COLOR_CYAN}================================================================${COLOR_RESET}"
echo -e "${COLOR_CYAN}    RISKBYTE SOC AGENT — ENTERPRISE INSTALLATION SYSTEM        ${COLOR_RESET}"
echo -e "${COLOR_CYAN}    Air-Gapped · Self-Hosted · Zero Telemetry Egress            ${COLOR_RESET}"
echo -e "${COLOR_CYAN}================================================================${COLOR_RESET}"

INSTALL_DIR="${RISKBYTE_HOME:-/opt/riskbyte}"
DATA_DIR="${INSTALL_DIR}/data"
SSL_DIR="${INSTALL_DIR}/deploy/nginx/ssl"

# 1. Check prerequisites
echo -e "\n${COLOR_AMBER}[1/5] Checking host system prerequisites...${COLOR_RESET}"
if ! command -v docker &> /dev/null; then
    echo -e "${COLOR_RED}ERROR: Docker engine is required but not installed.${COLOR_RESET}"
    exit 1
fi

if ! docker compose version &> /dev/null; then
    echo -e "${COLOR_RED}ERROR: Docker Compose v2 is required but not installed.${COLOR_RESET}"
    exit 1
fi

echo -e "${COLOR_GREEN}✓ Docker and Docker Compose v2 detected.${COLOR_RESET}"

# 2. Setup directory hierarchy
echo -e "\n${COLOR_AMBER}[2/5] Creating directory layout and permissions...${COLOR_RESET}"
mkdir -p "${DATA_DIR}/keys" "${SSL_DIR}" "${INSTALL_DIR}/rules" "${INSTALL_DIR}/intel"
chmod 700 "${DATA_DIR}/keys"
echo -e "${COLOR_GREEN}✓ Enclave storage initialized at ${DATA_DIR}.${COLOR_RESET}"

# 3. Generate self-signed TLS certificates for internal proxy if not present
echo -e "\n${COLOR_AMBER}[3/5] Verifying TLS certificates for Nginx proxy...${COLOR_RESET}"
if [ ! -f "${SSL_DIR}/server.crt" ]; then
    echo "Generating 4096-bit self-signed internal TLS certificate..."
    openssl req -x509 -nodes -days 365 -newkey rsa:4096 \
        -keyout "${SSL_DIR}/server.key" \
        -out "${SSL_DIR}/server.crt" \
        -subj "/C=US/ST=Security/L=Operations/O=RiskByte Customer/CN=soc.internal" \
        -addext "subjectAltName=DNS:localhost,IP:127.0.0.1" 2>/dev/null
    chmod 600 "${SSL_DIR}/server.key"
    echo -e "${COLOR_GREEN}✓ Internal TLS certificates generated.${COLOR_RESET}"
else
    echo -e "${COLOR_GREEN}✓ Existing TLS certificates found.${COLOR_RESET}"
fi

# 4. Initialize Secrets and .env if missing
echo -e "\n${COLOR_AMBER}[4/5] Securing enterprise credentials...${COLOR_RESET}"
if [ ! -f "${INSTALL_DIR}/.env" ]; then
    PG_PASS=$(openssl rand -hex 24)
    REDIS_PASS=$(openssl rand -hex 24)
    cat <<EOF > "${INSTALL_DIR}/.env"
# Auto-generated by RiskByte Enterprise Installer on $(date)
RISKBYTE_ENV=production
POSTGRES_PASSWORD=${PG_PASS}
REDIS_PASSWORD=${REDIS_PASS}
RISKBYTE_LLM_MODEL=llama3.1:8b
RISKBYTE_AIR_GAPPED=true
RISKBYTE_EGRESS_DENY=true
EOF
    chmod 600 "${INSTALL_DIR}/.env"
    echo -e "${COLOR_GREEN}✓ Generated cryptographically strong secrets in .env.${COLOR_RESET}"
fi

# 5. Launch containers
echo -e "\n${COLOR_AMBER}[5/5] Launching RiskByte SOC Agent containers...${COLOR_RESET}"
cd "${INSTALL_DIR}"
docker compose up -d

echo -e "\n${COLOR_GREEN}================================================================${COLOR_RESET}"
echo -e "${COLOR_GREEN}    INSTALLATION COMPLETE — RISKBYTE SOC AGENT IS READY         ${COLOR_RESET}"
echo -e "${COLOR_GREEN}================================================================${COLOR_RESET}"
echo -e "Web Console:       ${COLOR_CYAN}https://localhost:443${COLOR_RESET}"
echo -e "Default Admin:     ${COLOR_CYAN}admin@riskbyte.internal${COLOR_RESET}"
echo -e "Setup Wizard:      Click 'Setup Wizard' in top bar to enroll MFA & verify keys"
echo -e "Audit Log:         SHA-256 Chained & RSA-4096 Signed"
echo -e "Air-Gap Status:    ${COLOR_GREEN}EGRESS STRICTLY DENIED${COLOR_RESET}\n"
